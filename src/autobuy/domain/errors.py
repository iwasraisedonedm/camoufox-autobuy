"""Stable domain error taxonomy."""

from enum import StrEnum


class ErrorCode(StrEnum):
    CUSTOMER_NOT_LINKED = "CUSTOMER_NOT_LINKED"
    INVALID_TARGET = "INVALID_TARGET"
    INVALID_VARIANT = "INVALID_VARIANT"
    INVALID_QUANTITY = "INVALID_QUANTITY"
    INVALID_MAX_PRICE = "INVALID_MAX_PRICE"
    JOB_NOT_FOUND = "JOB_NOT_FOUND"
    JOB_NOT_ACTIVE = "JOB_NOT_ACTIVE"
    ENTITLEMENT_REQUIRED = "ENTITLEMENT_REQUIRED"
    ENTITLEMENT_EXPIRED = "ENTITLEMENT_EXPIRED"
    ENTITLEMENT_REVOKED = "ENTITLEMENT_REVOKED"
    ALLOWANCE_EXHAUSTED = "ALLOWANCE_EXHAUSTED"
    CONCURRENT_JOB_LIMIT_REACHED = "CONCURRENT_JOB_LIMIT_REACHED"
    RETAILER_PROFILE_NOT_FOUND = "RETAILER_PROFILE_NOT_FOUND"
    RETAILER_PROFILE_LOCKED = "RETAILER_PROFILE_LOCKED"
    RETAILER_REAUTH_REQUIRED = "RETAILER_REAUTH_REQUIRED"
    OUT_OF_STOCK = "OUT_OF_STOCK"
    PRICE_LIMIT_EXCEEDED = "PRICE_LIMIT_EXCEEDED"
    VARIANT_UNAVAILABLE = "VARIANT_UNAVAILABLE"
    PRODUCT_IDENTITY_MISMATCH = "PRODUCT_IDENTITY_MISMATCH"
    RETAILER_UNAVAILABLE = "RETAILER_UNAVAILABLE"
    ADD_TO_CART_FAILED = "ADD_TO_CART_FAILED"
    CHECKOUT_PREPARATION_FAILED = "CHECKOUT_PREPARATION_FAILED"
    PAYMENT_DECLINED = "PAYMENT_DECLINED"
    RETAILER_REJECTED = "RETAILER_REJECTED"
    PURCHASE_CONFIRMATION_FAILED = "PURCHASE_CONFIRMATION_FAILED"
    PURCHASE_AMBIGUOUS = "PURCHASE_AMBIGUOUS"
    DUPLICATE_PURCHASE_BLOCKED = "DUPLICATE_PURCHASE_BLOCKED"
    WORKER_UNAVAILABLE = "WORKER_UNAVAILABLE"
    WORKER_LOST = "WORKER_LOST"
    LEASE_INVALID = "LEASE_INVALID"
    LEASE_EXPIRED = "LEASE_EXPIRED"
    INTERNAL_ERROR = "INTERNAL_ERROR"


class DomainError(Exception):
    """Base exception carrying a stable machine code."""

    def __init__(self, code: ErrorCode, message: str) -> None:
        super().__init__(message)
        self.code = code
        self.message = message
